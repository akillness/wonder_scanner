const hash = (s) => [...s].reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 7);

export function notesFor(label, wonder, count) {
  const out = [];
  if (count >= 3) { const list = BY_CHAPTER[wonder.chapter]; out.push(list[hash(label) % list.length].replaceAll('{n}', wonder.name)); }
  if (count >= 10) out.push(BY_RARITY[wonder.rarity].replaceAll('{n}', wonder.name));
  return out;
}
